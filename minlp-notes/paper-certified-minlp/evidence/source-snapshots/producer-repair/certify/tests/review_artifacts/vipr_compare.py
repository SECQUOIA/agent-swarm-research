"""Prototype: compare the problem section of a VIPR file with the rational
master data regenerated by the checker (proposed fix for the VIPR-LP gap)."""
import sys, re
from fractions import Fraction
from collections import OrderedDict, Counter

def parse_vipr_problem(path):
    toks = []
    with open(path) as f:
        for line in f:
            if line.startswith("%"): continue
            toks.extend(line.split())
            if toks and toks[-1] == "RTP" or "RTP" in toks[-3:]:
                break
    it = iter(toks)
    def nxt(): return next(it)
    assert nxt() == "VER"; ver = nxt()
    assert nxt() == "VAR"; n = int(nxt()); names = [nxt() for _ in range(n)]
    assert nxt() == "INT"; k = int(nxt()); ints = {int(nxt()) for _ in range(k)}
    assert nxt() == "OBJ"; sense = nxt(); k = int(nxt())
    obj = {}
    for _ in range(k):
        i = int(nxt()); obj[i] = Fraction(nxt())
    assert nxt() == "CON"; m = int(nxt()); nb = int(nxt())
    cons = []
    for _ in range(m):
        name = nxt(); s = nxt(); rhs = Fraction(nxt()); p = nxt()
        if p == "OBJ":
            coefs = dict(obj)
        else:
            coefs = {}
            for _ in range(int(p)):
                i = int(nxt()); coefs[i] = coefs.get(i, Fraction(0)) + Fraction(nxt())
        cons.append((name, s, rhs, coefs))
    return names, ints, sense, obj, cons

def canon(sense, rhs, coefs, names):
    """Normalise to a hashable (sense, rhs, sorted coefs) with names; drop zero coefs."""
    items = tuple(sorted((names[i], c) for i, c in coefs.items() if c != 0))
    return (sense, rhs, items)

def expected_from_master(varnames, vtypes, box, rows, cuts, obj_coefs, obj_const):
    exp = Counter()
    for name, coefs, lb, ub in rows:
        if not coefs: continue
        items = tuple(sorted((v, c) for v, c in coefs.items() if c != 0))
        if lb is not None and ub is not None and lb == ub:
            exp[("E", lb, items)] += 1
        else:
            if lb is not None: exp[("G", lb, items)] += 1
            if ub is not None: exp[("L", ub, items)] += 1
    for name, coefs, b in cuts:
        items = tuple(sorted((v, c) for v, c in coefs.items() if c != 0))
        exp[("L", -b, items)] += 1
    for v in varnames:
        lb, ub = box[v]
        if lb is not None: exp[("G", lb, ((v, Fraction(1)),))] += 1
        if ub is not None: exp[("L", ub, ((v, Fraction(1)),))] += 1
    if obj_const != 0:
        exp[("G", Fraction(1), (("objconst", Fraction(1)),))] += 1
        exp[("L", Fraction(1), (("objconst", Fraction(1)),))] += 1
    return exp

def compare(vipr_path, varnames, vtypes, box, rows, cuts, obj_coefs, obj_const):
    names, ints, sense, obj, cons = parse_vipr_problem(vipr_path)
    names = [n[2:] if n.startswith("t_") else n for n in names]
    problems = []
    if sense != "min": problems.append("objective sense")
    if set(names) != set(varnames) | ({"objconst"} if obj_const != 0 else set()):
        problems.append(f"variable set differs: {set(names) ^ set(varnames)}")
    ints_names = {names[i] for i in ints}
    exp_ints = {v for v in varnames if vtypes[v] in ("I", "B")}
    if ints_names != exp_ints: problems.append(f"integer set differs: {ints_names ^ exp_ints}")
    objv = {names[i]: c for i, c in obj.items() if c != 0}
    expobj = {v: c for v, c in obj_coefs.items() if c != 0}
    if obj_const != 0: expobj["objconst"] = obj_const
    if objv != expobj: problems.append("objective differs")
    got = Counter(canon(s, rhs, coefs, names) for (_, s, rhs, coefs) in cons)
    exp = expected_from_master(varnames, vtypes, box, rows, cuts, obj_coefs, obj_const)
    # every expected constraint must be present in the VIPR problem (extra VIPR
    # constraints would make the VIPR problem *more* constrained -> unsound, so
    # require exact multiset equality)
    missing = exp - got; extra = got - exp
    if missing: problems.append(f"{sum(missing.values())} master constraints missing from VIPR, e.g. {list(missing)[:2]}")
    if extra: problems.append(f"{sum(extra.values())} VIPR constraints not in master, e.g. {list(extra)[:2]}")
    return problems

